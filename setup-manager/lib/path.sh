#!/usr/bin/env bash
# Безпека шляхів.

# path_ok_rel — чи безпечний відносний шлях.
# Забороняє: абсолютний, '.', '..', будь-яке '..' у середині, './', новий рядок.
path_ok_rel() {
    local p="$1"
    [[ -n "$p" && "$p" != /* && "$p" != '.' && "$p" != '..' \
       && "$p" != *'/../'* && "$p" != ../* && "$p" != */.. \
       && "$p" != *'/./'* && "$p" != ./* && "$p" != *$'\n'* ]]
}

# path_ok_abs — чи безпечний абсолютний шлях.
# Забороняє '..' і symlink у БУДЬ-якому компоненті шляху.
path_ok_abs() {
    local p="$1"
    [[ "$p" == /* && "$p" != *'/../'* && "$p" != *$'\n'* ]] || return 1
    local cur="$p"
    while [[ "$cur" != / && -n "$cur" ]]; do
        [[ ! -L "$cur" ]] || return 1
        cur="$(dirname -- "$cur")"
    done
}
