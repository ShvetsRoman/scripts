-- ============================================================
-- ESCAPE СПЕЦІАЛЬНИХ СИМВОЛІВ LANGMAP
-- ============================================================

local function escape_langmap(value)
	return value:gsub("\\", "\\\\"):gsub(",", "\\,"):gsub(";", "\\;"):gsub('"', '\\"'):gsub("|", "\\|")
end

-- ------------------------------------------------------------
-- ФІНАЛЬНЕ ЗНАЧЕННЯ
-- ------------------------------------------------------------

local escaped = {}

for _, pair in ipairs(map) do
	escaped[#escaped + 1] = escape_langmap(pair)
end

vim.opt.langmap = table.concat(escaped, ",")
