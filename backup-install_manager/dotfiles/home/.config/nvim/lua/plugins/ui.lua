-- ============================================================
-- КОЛЬОРОВА ПАЛІТРА NORDIC
-- ============================================================

local colors = {
	-- Спільний фон центральних секцій Lualine
	status_bg = "#3B4252",

	-- Основний текст
	fg = "#D8DEE9",

	-- Неактивний текст
	muted = "#8294AB",

	-- Акценти режимів
	normal = "#D08770",
	insert = "#A3BE8C",
	visual = "#B48EAD",
	replace = "#BF616A",
	command = "#EBCB8B",

	-- Акцент крайньої правої секції
	location = "#D08770",

	-- Темний текст для контрастних секцій
	dark = "#242933",
}

-- ============================================================
-- ТЕМА LUALINE
--
-- Створюємо тему безпосередньо у цьому файлі.
-- Не використовуємо require("lualine.themes.auto").
-- ============================================================

local function lualine_theme()
	-- Однакове оформлення центральних секцій.
	local function section()
		return {
			fg = colors.fg,
			bg = colors.status_bg,
		}
	end

	-- Оформлення панелі для конкретного режиму.
	local function mode_theme(accent)
		return {
			-- Ліва секція з назвою режиму.
			a = {
				fg = colors.dark,
				bg = accent,
				gui = "bold",
			},

			-- Git та діагностика.
			b = section(),

			-- Шлях поточного файла.
			c = section(),

			-- Кодування та тип файла.
			x = section(),

			-- Відсоток прокручування.
			y = section(),

			-- Позиція курсора.
			z = {
				fg = colors.dark,
				bg = colors.location,
				gui = "bold",
			},
		}
	end

	return {
		normal = mode_theme(colors.normal),
		insert = mode_theme(colors.insert),
		visual = mode_theme(colors.visual),
		replace = mode_theme(colors.replace),
		command = mode_theme(colors.command),

		-- Неактивне вікно.
		inactive = {
			a = section(),
			b = section(),
			c = section(),
			x = section(),
			y = section(),
			z = section(),
		},
	}
end

-- ============================================================
-- ПЛАГІНИ ІНТЕРФЕЙСУ
-- ============================================================

return {
	-- ========================================================
	-- ІКОНКИ ФАЙЛІВ
	-- ========================================================

	{
		"nvim-tree/nvim-web-devicons",

		-- Завантажувати за потреби.
		lazy = true,

		opts = {
			-- Кольорові іконки.
			color_icons = true,

			-- Іконки для невідомих типів файлів.
			default = true,
		},
	},

	-- ========================================================
	-- LUALINE
	-- Нижня панель стану Neovim
	-- ========================================================

	{
		"nvim-lualine/lualine.nvim",

		-- Завантажувати після основного запуску.
		event = "VeryLazy",

		dependencies = {
			"nvim-tree/nvim-web-devicons",
		},

		opts = {
			-- ====================================================
			-- ОСНОВНІ НАЛАШТУВАННЯ
			-- ====================================================

			options = {
				-- Власна тема Nordic.
				theme = lualine_theme(),

				-- Показувати іконки.
				icons_enabled = true,

				-- Одна спільна панель для всіх вікон.
				globalstatus = true,

				-- Роздільники компонентів.
				component_separators = {
					left = "│",
					right = "│",
				},

				-- Без великих роздільників між секціями.
				section_separators = {
					left = "",
					right = "",
				},

				-- Не вимикати панель для окремих типів.
				disabled_filetypes = {
					statusline = {},
					winbar = {},
				},
			},

			-- ====================================================
			-- СЕКЦІЇ НИЖНЬОЇ ПАНЕЛІ
			-- ====================================================

			sections = {
				-- Режим Neovim.
				lualine_a = {
					"mode",
				},

				-- Git та діагностика LSP.
				lualine_b = {
					"branch",
					"diff",
					"diagnostics",
				},

				-- Поточний файл.
				lualine_c = {
					{
						"filename",

						-- Відносний шлях.
						path = 1,
					},
				},

				-- Кодування, формат рядків і тип файла.
				lualine_x = {
					"encoding",
					"fileformat",
					"filetype",
				},

				-- Відсоток положення у файлі.
				lualine_y = {
					-- Вертикальний роздільник після типу файла
					{
						function()
							return " "
						end,

						color = {
							fg = "#D8DEE9",
							bg = "#3B4252",
						},

						padding = {
							left = 0,
							right = 1,
						},
					},
					"progress",
				},

				-- Номер рядка та колонка.
				lualine_z = {
					"location",
				},
			},

			-- ====================================================
			-- НЕАКТИВНІ ВІКНА
			-- ====================================================

			inactive_sections = {
				lualine_a = {},
				lualine_b = {},

				lualine_c = {
					"filename",
				},

				lualine_x = {
					"location",
				},

				lualine_y = {},
				lualine_z = {},
			},

			-- ====================================================
			-- ІНШІ ПАНЕЛІ
			-- ====================================================

			-- Не створювати окрему панель вкладок.
			tabline = {},

			-- Не створювати верхній Winbar.
			winbar = {},
			inactive_winbar = {},

			-- ====================================================
			-- РОЗШИРЕННЯ
			-- ====================================================

			extensions = {
				"lazy",
				"man",
				"quickfix",
			},
		},
	},

	-- ========================================================
	-- WHICH-KEY
	-- Підказки гарячих клавіш
	-- ========================================================

	{
		"folke/which-key.nvim",

		-- Завантажувати після основного запуску.
		event = "VeryLazy",

		opts = {
			-- Оформлення меню в стилі Helix.
			preset = "helix",

			-- Затримка появи підказок.
			delay = 300,

			-- Символи меню.
			icons = {
				breadcrumb = "»",
				separator = "➜",
				group = "+",
			},

			-- Заокруглене floating-вікно.
			win = {
				border = "rounded",
				padding = { 1, 2 },
			},

			-- Розміри меню.
			layout = {
				width = {
					min = 20,
					max = 50,
				},

				spacing = 3,
			},
		},

		-- ====================================================
		-- ГАРЯЧІ КЛАВІШІ
		-- ====================================================

		keys = {
			{
				"<leader>?",

				function()
					require("which-key").show({
						global = false,
					})
				end,

				desc = "Локальні клавіші",
			},
		},

		-- ====================================================
		-- ГРУПИ КЛАВІШ
		-- ====================================================

		config = function(_, opts)
			local wk = require("which-key")

			-- Ініціалізувати WhichKey.
			wk.setup(opts)

			-- Зареєструвати групи клавіш.
			wk.add({
				{ "<leader>f", group = "Пошук" },
				{ "<leader>g", group = "Git" },
				{ "<leader>l", group = "LSP" },
				{ "<leader>b", group = "Буфери" },
				{ "<leader>u", group = "UI" },
			})
		end,
	},
}
